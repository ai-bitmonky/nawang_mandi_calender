#!/usr/bin/env node
/* Generates lib/data.ts from the prototype's data file (data/source-data.js).
   Usage: npm run gen-data [-- path/to/data.js]   (default: data/source-data.js, or $MANDI_DATA)
   data.js is evaluated in an isolated vm context; only plain values come out. */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const src = path.resolve(process.argv[2] || process.env.MANDI_DATA || path.join(root, "data", "source-data.js"));
const code = fs.readFileSync(src, "utf8");

const out = vm.runInNewContext(
  code + "\n;({ZONES,STATES,REGION,MN,MFULL,SHAPE,DATA,SHAPE_FIX,R,SUPPLY,REACH,HINDI})",
  {},
  { filename: path.basename(src) },
);

/* SHAPE holds functions returning SVG markup: call each once to freeze it to a string. */
const SHAPES = Object.fromEntries(Object.entries(out.SHAPE).map(([k, f]) => [k, f()]));
/* data.js already applied SHAPE_FIX to DATA in place; do it again so this never depends on that. */
const DATA = out.DATA.map((d) => ({ ...d, s: out.SHAPE_FIX[d.n] || d.s, z: { ...d.z } }));
for (const d of DATA) {
  if (!SHAPES[d.s]) throw new Error(`Unknown shape "${d.s}" for ${d.n}`);
  if (!out.HINDI[d.n]) throw new Error(`Missing Hindi name for ${d.n}`);
}

const j = (v) => JSON.stringify(v);
const lines = (obj, fmt = j) =>
  "{\n" + Object.entries(obj).map(([k, v]) => `  ${j(k)}: ${fmt(v)},`).join("\n") + "\n}";

const ts = `/* AUTO-GENERATED by scripts/gen-data.mjs from data/source-data.js. Do not edit by hand.
   Regenerate: npm run gen-data */

export type ZoneKey = "N" | "LA" | "KA" | "HM" | "W" | "S" | "E" | "NE";
export type Range = readonly [number, number];
export type Item = {
  /** English name */ n: string;
  /** Hinglish / local name */ l: string;
  t: "fruit" | "veg";
  /** shape key in SHAPES */ s: string;
  /** main colour */ c: string;
  /** second colour */ c2: string;
  /** season per climate zone, [start month, end month], may wrap the year */
  z: Partial<Record<ZoneKey, Range>>;
};
/** [dish, one-line description, space-separated region tags (zone keys, IN, INT)] */
export type Recipe = readonly [string, string, string];

export const ZONES: Record<ZoneKey, string> = ${j(out.ZONES)};

export const STATES: ReadonlyArray<readonly [string, ZoneKey]> = [
${out.STATES.map((s) => "  " + j(s) + ",").join("\n")}
];

export const REGION: Record<ZoneKey, string> = ${j(out.REGION)};

export const MN = ${j(out.MN)} as const;
export const MFULL = ${j(out.MFULL)} as const;

/** SVG markup for each silhouette, drawn in a 64×64 box. Colours come from --a / --b / --lf / --st. */
export const SHAPES: Record<string, string> = ${lines(SHAPES)};

export const SHAPE_FIX: Record<string, string> = ${j(out.SHAPE_FIX)};

export const DATA: ReadonlyArray<Item> = [
${DATA.map((d) => "  " + j(d) + ",").join("\n")}
];

export const R: Record<string, ReadonlyArray<Recipe>> = ${lines(out.R)};

/** Zones that ship each item to other states. Missing = stays local. */
export const SUPPLY: Record<string, ReadonlyArray<ZoneKey>> = ${lines(out.SUPPLY)};

/** Items that only travel to nearby zones. */
export const REACH: Record<string, ReadonlyArray<ZoneKey>> = ${j(out.REACH)};

export const HINDI: Record<string, string> = ${lines(out.HINDI)};
`;

const dst = path.join(root, "lib", "data.ts");
fs.writeFileSync(dst, ts);
console.log(`Wrote ${path.relative(root, dst)}: ${DATA.length} items, ${Object.keys(SHAPES).length} shapes, ${Object.keys(out.R).length} recipe lists.`);
